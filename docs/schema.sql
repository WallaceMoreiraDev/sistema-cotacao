-- 11. Tabela de Perfis de Usuários (Profiles)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin', 'funcionario')),
  job_title TEXT NOT NULL,
  department TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
  needs_password_change BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Trigger para criar perfil automaticamente se um usuário for inserido em auth.users
CREATE OR REPLACE FUNCTION public.handle_new_user() 
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, role, job_title, department)
  VALUES (new.id, COALESCE(new.raw_user_meta_data->>'full_name', 'Usuário ' || split_part(new.email, '@', 1)), 
          COALESCE(new.raw_user_meta_data->>'role', 'funcionario'),
          COALESCE(new.raw_user_meta_data->>'job_title', 'Não definido'),
          COALESCE(new.raw_user_meta_data->>'department', 'Não definido'))
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Segurança da tabela profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Usuários podem ler seu próprio perfil
CREATE POLICY "Usuários podem ler o próprio perfil" ON public.profiles 
  FOR SELECT USING (auth.uid() = id);

-- Qualquer pessoa logada pode ler perfis (para ver quem fez o protocolo, etc)
CREATE POLICY "Qualquer logado pode ler perfis da empresa" ON public.profiles 
  FOR SELECT USING (auth.role() = 'authenticated');

-- Apenas admins podem atualizar os perfis (via banco)
CREATE POLICY "Admins podem atualizar perfis" ON public.profiles 
  FOR UPDATE USING (
    (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin'
  );

